def gcd_0419_0003(left, right):
    while right:
        left, right = right, left % right
    return abs(left)


def lcm_0419_0003(left, right):
    if left == 0 or right == 0:
        return 0
    return abs(left * right) // gcd_0419_0003(left, right)

def matrix_multiply_0419_0004(left, right):
    rows = len(left)
    columns = len(right[0])
    shared = len(right)
    result = [[0] * columns for _ in range(rows)]
    for row in range(rows):
        for column in range(columns):
            total = 0
            for offset in range(shared):
                total += left[row][offset] * right[offset][column]
            result[row][column] = total
    return result

