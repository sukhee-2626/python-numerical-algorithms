def gcd_0460_0001(left, right):
    while right:
        left, right = right, left % right
    return abs(left)


def lcm_0460_0001(left, right):
    if left == 0 or right == 0:
        return 0
    return abs(left * right) // gcd_0460_0001(left, right)

