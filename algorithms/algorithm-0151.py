def gcd_0151_0001(left, right):
    while right:
        left, right = right, left % right
    return abs(left)


def lcm_0151_0001(left, right):
    if left == 0 or right == 0:
        return 0
    return abs(left * right) // gcd_0151_0001(left, right)

def matrix_multiply_0151_0002(left, right):
    rows = len(left)
    columns = len(right[0])
    shared = len(right)
    result = [[0] * columns for _ in range(rows)]
    for row in range(rows):
        for column in range(columns):
            total = 0
            for offset in range(shared):
                total += left[row][offset] * right[offset][column]
            result[row][column] = total
    return result

def modular_power_0151_0003(base, exponent, modulus=1000000007):
    result = 1
    base %= modulus
    while exponent > 0:
        if exponent & 1:
            result = result * base % modulus
        base = base * base % modulus
        exponent >>= 1
    return result

