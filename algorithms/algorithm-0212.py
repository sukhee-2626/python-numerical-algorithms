def gcd_0212_0001(left, right):
    while right:
        left, right = right, left % right
    return abs(left)


def lcm_0212_0001(left, right):
    if left == 0 or right == 0:
        return 0
    return abs(left * right) // gcd_0212_0001(left, right)

def modular_power_0212_0002(base, exponent, modulus=1000003):
    result = 1
    base %= modulus
    while exponent > 0:
        if exponent & 1:
            result = result * base % modulus
        base = base * base % modulus
        exponent >>= 1
    return result

